<#
  Zips the mealawe-customer SOURCE ONLY (no node_modules, build output, caches, git history, local secrets).

  Usage (from anywhere):
    powershell -ExecutionPolicy Bypass -File scripts\zip-source.ps1
    powershell -ExecutionPolicy Bypass -File scripts\zip-source.ps1 -OutDir D:\backups
    powershell -ExecutionPolicy Bypass -File scripts\zip-source.ps1 -IncludeGit

  Output: <OutDir>\mealawe-customer-source-<yyyyMMdd-HHmmss>.zip   (default OutDir = your Desktop)
#>
param(
  [string]$Source = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path,
  [string]$OutDir = [Environment]::GetFolderPath('Desktop'),
  [switch]$IncludeGit
)

$ErrorActionPreference = 'Stop'

# Directories skipped at ANY depth.
$excludeDirs = @(
  'node_modules', '.next', '.turbo', '.expo', '.cache', '.parcel-cache', '.vite',
  'dist', 'build', 'out', 'coverage', '.nyc_output', '.eas', '.gradle',
  'Pods', 'DerivedData', '.idea', '__pycache__', '.vercel'
)
if (-not $IncludeGit) { $excludeDirs += '.git' }

# Native folders generated by `expo prebuild` (only the top-level ones inside apps/mobile).
$excludeDirs += (Join-Path $Source 'apps\mobile\android')
$excludeDirs += (Join-Path $Source 'apps\mobile\ios')

# Files skipped anywhere. Local env files hold secrets/keys; .env.example is kept on purpose.
$excludeFiles = @(
  '*.log', '*.tsbuildinfo', '*.zip', '*.tgz', '.DS_Store', 'Thumbs.db',
  '.env', '.env.local', '.env.*.local', '.env.development', '.env.production',
  'repomix-output.xml', 'npm-debug.log*', 'yarn-error.log*'
)

if (-not (Test-Path $Source)) { throw "Source folder not found: $Source" }
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null

$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$zipPath = Join-Path $OutDir "mealawe-customer-source-$stamp.zip"
$stage = Join-Path ([IO.Path]::GetTempPath()) "mealawe-customer-src-$stamp"

Write-Host "Source : $Source"
Write-Host "Staging: $stage"
Write-Host "Output : $zipPath"

try {
  # robocopy: /E subfolders, /XD /XF exclusions, quiet; exit codes 0-7 are success.
  $args = @($Source, $stage, '/E', '/NFL', '/NDL', '/NJH', '/NJS', '/NP', '/R:1', '/W:1', '/XD') + $excludeDirs + @('/XF') + $excludeFiles
  & robocopy @args | Out-Null
  if ($LASTEXITCODE -ge 8) { throw "robocopy failed (exit code $LASTEXITCODE)" }

  $files = (Get-ChildItem -Path $stage -Recurse -File | Measure-Object)
  Write-Host ("Copied {0} files, compressing..." -f $files.Count)

  if (Test-Path $zipPath) { Remove-Item $zipPath -Force }
  # tar ships with Windows 10+ and handles long paths better than Compress-Archive.
  Push-Location $stage
  try { & tar.exe -a -c -f $zipPath * } finally { Pop-Location }
  if ($LASTEXITCODE -ne 0) { throw "tar failed (exit code $LASTEXITCODE)" }

  $mb = [math]::Round((Get-Item $zipPath).Length / 1MB, 2)
  Write-Host "Done: $zipPath ($mb MB)" -ForegroundColor Green
}
finally {
  if (Test-Path $stage) { Remove-Item $stage -Recurse -Force -ErrorAction SilentlyContinue }
}
