const { withPodfile } = require('@expo/config-plugins');

/**
 * With `$RNFirebaseDisableSPM = true` (see app.json's @react-native-firebase/app
 * plugin config), Firebase resolves via CocoaPods instead of SPM. Its pods
 * (GoogleUtilities, nanopb, PromisesObjC, ...) don't declare Swift modules,
 * which breaks static-library integration ("cannot yet be integrated as
 * static libraries ... does not define modules"). CocoaPods' own fix is
 * `use_modular_headers!` — Expo's autolinking already does this per-pod for
 * Expo modules, but Firebase's transitive pods aren't covered by that.
 * Podfile is regenerated by `expo prebuild` on every EAS build, so this must
 * be injected via a config plugin rather than hand-edited.
 *
 * Must stay registered in app.json's `plugins` array (alongside the
 * `disableSPM` config above it) — dropping just this one silently breaks iOS
 * builds with a `does not define modules` / `cannot yet be integrated as
 * static libraries` pod install failure, since disableSPM alone re-introduces
 * GoogleUtilities et al. via CocoaPods without this fix for them.
 */
function withFirebaseModularHeaders(config) {
  return withPodfile(config, (config) => {
    const marker = 'use_modular_headers!';
    if (config.modResults.contents.includes(marker)) {
      return config;
    }
    const anchor = /^prepare_react_native_project!$/m;
    if (!anchor.test(config.modResults.contents)) {
      throw new Error('withFirebaseModularHeaders: could not find prepare_react_native_project! to patch');
    }
    config.modResults.contents = config.modResults.contents.replace(
      anchor,
      (match) => `${marker}\n${match}`,
    );
    return config;
  });
}

module.exports = withFirebaseModularHeaders;
